package config

// The web UI's Config page is generated from Schema(). Every typed setting gets a real input;
// a setting of type "any" (a free-form map such as a deployer's options) falls back to a raw YAML
// text box, which in practice means editing onett.yaml by hand. The goal is that every setting
// can be set from the UI, so these tests make that visible and stop it getting worse:
//
//   - knownGaps lists today's `any` paths, each with what UI would close it. It is a ratchet:
//     the test also fails when an entry no longer matches an `any` node, so whoever closes a
//     gap must delete its entry.
//   - fileOnly lists `any` paths that must stay file-only on purpose, each with a reason. It
//     should stay empty or nearly so; do not park real gaps here.
//
// Do not add a new path to either list without the owner's agreement. A new setting should get
// a typed schema instead.
//
// The same walk generates docs/config-ui-coverage.md. Run
// `go test ./internal/config -run TestConfigCoverageDoc -update` to rewrite it.

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

var updateCoverageDoc = flag.Bool("update", false, "rewrite docs/config-ui-coverage.md from the schema")

const coverageDocPath = "../../docs/config-ui-coverage.md"

// fileOnly: settings that must stay file-only. Path -> reason.
var fileOnly = map[string]string{}

// knownGaps: `any` settings the UI edits only as raw YAML. Path -> the UI that would close it.
// Empty: the per-type options of notifiers, channels, deployers and observers have typed editors.
var knownGaps = map[string]string{}

type schemaRow struct {
	Path string
	Type string
}

// schemaRows lists every node of the schema except the root, depth first, with a dotted path in
// which `*` stands for a map key or a list element.
func schemaRows() []schemaRow {
	var rows []schemaRow
	var walk func(n SchemaNode, path string)
	walk = func(n SchemaNode, path string) {
		if path != "" {
			rows = append(rows, schemaRow{Path: path, Type: n.Type})
		}
		for _, f := range n.Fields {
			walk(f, joinPath(path, f.Key))
		}
		if n.Item != nil {
			walk(*n.Item, joinPath(path, "*"))
		}
		// A variant is covered by its per-type sections: notify.*.options[telegram].bot_token_env.
		names := make([]string, 0, len(n.Variants))
		for name := range n.Variants {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			variant := n.Variants[name]
			for _, f := range variant.Fields {
				walk(f, fmt.Sprintf("%s[%s].%s", path, name, f.Key))
			}
		}
	}
	walk(Schema(), "")
	return rows
}

func joinPath(base, key string) string {
	if base == "" {
		return key
	}
	return base + "." + key
}

func TestEveryConfigFieldHasStructuredEditor(t *testing.T) {
	anyPaths := map[string]bool{}
	for _, r := range schemaRows() {
		if r.Type == "any" {
			anyPaths[r.Path] = true
		}
	}
	var problems []string
	for p := range anyPaths {
		_, gap := knownGaps[p]
		_, file := fileOnly[p]
		if !gap && !file {
			problems = append(problems, fmt.Sprintf("config field %s has no structured editor: give it a typed schema, or add it to knownGaps/fileOnly with a reason (needs the owner's agreement)", p))
		}
	}
	for name, list := range map[string]map[string]string{"knownGaps": knownGaps, "fileOnly": fileOnly} {
		for p, note := range list {
			if !anyPaths[p] {
				problems = append(problems, fmt.Sprintf("%s lists %s, which is no longer a free-form (any) field: delete the entry", name, p))
			}
			if strings.TrimSpace(note) == "" {
				problems = append(problems, fmt.Sprintf("%s entry %s needs a note", name, p))
			}
		}
	}
	sort.Strings(problems)
	assert.Empty(t, problems, strings.Join(problems, "\n"))
}

func TestCoverageListsDoNotOverlap(t *testing.T) {
	for p := range fileOnly {
		assert.NotContains(t, knownGaps, p, "%s is in both lists", p)
	}
}

// coverageDocHead and coverageDocTail are the hand-written parts of the doc.
const coverageDocHead = "<!-- Generated by TestConfigCoverageDoc; edit the table by changing the schema, not this file.\n" +
	"     Run: go test ./internal/config -run TestConfigCoverageDoc -update -->\n\n" +
	"# Config UI coverage\n\n" +
	"The web UI's Config page is built from the config schema (`internal/config/schema.go`). A setting\n" +
	"is **covered** when the page gives it a typed input (text, number, switch, duration, or a\n" +
	"section/list/map of those). A `variant` is an `options` map whose fields depend on the sibling\n" +
	"`type`: the page shows the fields of the selected type, so each is listed as `path[type].key`.\n" +
	"A setting of type `any` is a free-form value that the page edits as a raw YAML text box, so it\n" +
	"is **not covered**. `*` in a path stands for a map key (a project name) or a list element.\n\n" +
	"The frontend renders every node of the schema: `NodeEditor` in\n" +
	"`web/src/components/config/ConfigSection.tsx` handles each type and nothing is skipped, so the\n" +
	"`any` rows below are the complete list of gaps. `TestEveryConfigFieldHasStructuredEditor` fails\n" +
	"when a new `any` field appears or a gap is closed without its entry being removed.\n\n" +
	"| Path | Type | Covered | Note |\n|---|---|---|---|\n"

func renderCoverageDoc() string {
	var b strings.Builder
	b.WriteString(coverageDocHead)
	for _, r := range schemaRows() {
		covered, note := "yes", ""
		if r.Type == "any" {
			covered = "no"
			if n, ok := knownGaps[r.Path]; ok {
				note = "Gap: " + n
			} else if n, ok := fileOnly[r.Path]; ok {
				covered = "file-only"
				note = n
			} else {
				note = "unlisted"
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.Path, r.Type, covered, note)
	}
	b.WriteString(coverageDocTail)
	return b.String()
}

func TestConfigCoverageDoc(t *testing.T) {
	want := renderCoverageDoc()
	if *updateCoverageDoc {
		require.NoError(t, os.WriteFile(coverageDocPath, []byte(want), 0o644))
		return
	}
	got, err := os.ReadFile(coverageDocPath)
	require.NoError(t, err)
	require.Equal(t, want, string(got), "docs/config-ui-coverage.md is stale: run `go test ./internal/config -run TestConfigCoverageDoc -update`")
}

